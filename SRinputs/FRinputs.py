def FRDateInput(msg : str = "Write your birthday: ", format : int = 0):
    """
    Generates a fake date and simulates it as standard input.

    The function temporarily redirects sys.stdin to a date generated by the 
    Faker library using a specific format from a predefined list, allowing 
    the input() function to read a random date string.

    Args:
        msg (str, optional): The message to display to the user. Defaults to 'Write your birthday: '.
        format (int, optional): The index of the date format to use (0 to 3). Defaults to 0.

    Returns:
        str: The fake date generated and read from the simulated input.
    """
    temp_stdin = sys.stdin
    try:
        format = int(format)
        safeIndex = format % len(DATE_FORMATS)
        sys.stdin = io.StringIO(fake.date(DATE_FORMATS[safeIndex]))
        date = input(msg)
        sleep(wait)
        print(date)
        return date
    
    except ValueError:
        print(f"The format value must be an integer between 0 and 3 not {format}")
    except Exception as e:
        print(f"Error {e}")
    finally:
        sys.stdin = temp_stdin

