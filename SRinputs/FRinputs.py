def FRHandleInput(msg : str = "Write your handle: ", name : str = ""):
    """
    Generates a fake social media handle and simulates it as standard input.

    The function constructs a handle starting with '@', using a portion of a 
    provided or generated name, and appends random digits. It then redirects 
    sys.stdin to this handle, allowing the input() function to read it.

    Args:
        msg (str, optional): The message to display to the user. Defaults to 'Write your handle: '.
        name (str, optional): A base name to construct the handle. If not provided, 
                              a random name is generated.

    Returns:
        str: The fake social media handle generated and read from the simulated input.
    """
    temp_stdin = sys.stdin
    try:
        if not name:
            name = fake.name().replace(" ", "")
        
        auxHandle = "@" + name[:len(name)//3] + "_" + name[1 + len(name)//3:] +  fake.numerify("@@@@")
        sys.stdin = io.StringIO(auxHandle)
        handle = input(msg)
        sleep(wait)
        print(handle)
        return handle
    
    except Exception as e:
        print(f"Error: {e}")
    finally:
        sys.stdin = temp_stdin