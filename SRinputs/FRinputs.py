import sys
from faker import Faker
from time import sleep
import io

"""Name, Url, Mail, Date, PhoneNumber, Id, Handle"""
wait = 0.4

fake = Faker()

GENDERS = {
        'male' : fake.name_male,
        'female' : fake.name_female,
        'nonbinary' : fake.name_nonbinary,
        'default' : fake.name
    }

DATE_FORMATS = ["%Y-%m-%d", "%d/%m/%Y", "%m-%d-%Y", "%d/%m/%y"]

def FRNameInput(msg : str = 'Write a name: ', gender : str = 'default'):
    """
    Generates a fake name based on gender and simulates it as standard input.

    The function temporarily redirects sys.stdin to a string generated by the 
    Faker library, allowing the input() function to read a random name.

    Args:
        msg (str, optional): The message to display to the user. Defaults to 'Write a name: '.
        gender (str, optional): The gender category for the name ('male', 'female', 'nonbinary', 'default'). 
                                Defaults to 'default'.
    Returns:
        str: The fake name generated and read from the simulated input.
    """
    temp_stdin = sys.stdin
    try:
        clean_gender = gender.lower()
        if clean_gender not in GENDERS:
            clean_gender = 'default'
        sys.stdin = io.StringIO(GENDERS.get(clean_gender)())
        name = input(msg)
        sleep(wait)
        print(name)
        return name
    
    except TypeError as e:
        print(f'Error: {e}')
    finally:  
        sys.stdin = temp_stdin

